"""Workspace building: YAML -> cabinetry -> ``ws.json`` (+ ``patchset.json``).

Outputs in ``<OutputDir>/<Name>/``:

* ``ws.json``               - pyhf workspace.  For exclusion fits this is the
  background-only workspace (HEPData "BkgOnly.json" style)
* ``patchset.json``         - (exclusion) one pyhf patch per signal point adding the
  signal sample; ``pyhf patchset apply`` / the fit runner combine both
* ``meta.json``             - region roles, sample colours/labels, signal points ...
* ``cabinetry_config.yaml`` - the full cabinetry configuration that was used
* ``histograms/``           - cabinetry template histograms
"""

from __future__ import annotations

import copy
import logging
import pathlib
import shutil
import time
from typing import Any, Dict, List, Optional, Sequence

import cabinetry
import numpy as np
import pyhf

from fit2l3l.utils import as_list, dump_yaml, load_yaml, write_json
from fit2l3l.workspace import postprocess
from fit2l3l.workspace.composer import Composition, compose
from fit2l3l.workspace.templates import TemplateEngine

log = logging.getLogger(__name__)

CONFIG_HEADER = """
cabinetry configuration generated by fit2l3l from {source}.
Templates were produced through a cabinetry Router (fit2l3l.workspace.templates):
  * Tree "{{prefix}}_X"            -> tree X of the sample (prefix = sample tree prefix)
  * Weight "{{weight}}*f"          -> nominal weight of the sample times f
  * Weight "{{weight:a->b}}"       -> nominal weight with factor a replaced by b
  * Up/Down {{}} (empty)           -> template built by fit2l3l (data-driven yields,
                                    theory uncertainties from JSON, ...)
"""


def _signal_only_config(comp: Composition, signal: str, folder: pathlib.Path) -> Dict[str, Any]:
    cfg = comp.config_for(signal)
    cfg["Samples"] = [s for s in cfg["Samples"] if s["Name"] == signal]
    cfg["Systematics"] = [s for s in cfg.get("Systematics", []) if signal in as_list(s.get("Samples"))]
    cfg["Systematics"] = [dict(s, Samples=[signal]) for s in cfg["Systematics"]]
    cfg["NormFactors"] = [nf for nf in cfg["NormFactors"] if signal in as_list(nf.get("Samples"))]
    cfg["General"] = dict(cfg["General"], HistogramFolder=str(folder))
    return cfg


def _build_ws(engine: TemplateEngine, comp: Composition, config: Dict[str, Any], pruning) -> Dict[str, Any]:
    pathlib.Path(config["General"]["HistogramFolder"]).mkdir(parents=True, exist_ok=True)
    engine.build(config)
    postprocess.normalize_systematics(config, comp.registry)
    with np.errstate(divide="ignore", invalid="ignore"):
        ws = cabinetry.workspace.build(config, with_validation=False)
    ws = postprocess.postprocess_workspace(ws, comp.registry, pruning)
    pyhf.Workspace(ws)  # validation
    return ws


def _signal_patch(
    engine: TemplateEngine, comp: Composition, bkg_ws: Dict[str, Any], point, folder: pathlib.Path, pruning
) -> Dict[str, Any]:
    cfg = _signal_only_config(comp, point.name, folder)
    folder.mkdir(parents=True, exist_ok=True)
    engine.build(cfg)
    builder = cabinetry.workspace.WorkspaceBuilder(cfg)
    with np.errstate(divide="ignore", invalid="ignore"):
        channels = builder.channels()
    ops: List[Dict[str, Any]] = []
    index = {c["name"]: i for i, c in enumerate(bkg_ws["channels"])}
    for channel in channels:
        samples = [s for s in channel["samples"] if s["name"] == point.name]
        postprocess.postprocess_samples(channel["name"], samples, comp.registry, pruning)
        for sample in samples:
            ops.append({"op": "add", "path": f"/channels/{index[channel['name']]}/samples/-", "value": sample})
    poi = comp.meta["poi"]
    ops.append({"op": "replace", "path": "/measurements/0/config/poi", "value": poi})
    params = bkg_ws["measurements"][0]["config"]["parameters"]
    names = {p["name"] for p in params}
    for par in builder.measurements()[0]["config"]["parameters"]:
        if par["name"] not in names:
            ops.append({"op": "add", "path": "/measurements/0/config/parameters/-", "value": par})
    if point.name in comp.registry.lumi_samples and "lumi" not in names:
        ops.append(
            {"op": "add", "path": "/measurements/0/config/parameters/-", "value": postprocess.lumi_parameter(comp.registry)}
        )
    metadata = {
        "name": point.name,
        "values": [float(m) for m in point.masses],
        "dsid": point.dsid,
        "xsec_fb": point.xsec,
        "xsec_rel_up": point.xsec_rel_up,
        "xsec_rel_down": point.xsec_rel_down,
    }
    return {"metadata": metadata, "patch": ops}


def build_workspace(
    config: Any,
    *,
    overrides: Optional[Dict[str, Any]] = None,
    points: Optional[Sequence[str]] = None,
    n_workers: int = 1,
    keep_histograms: bool = True,
    write_full_workspaces: bool = False,
) -> Dict[str, pathlib.Path]:
    """Builds the workspace described by a workspace YAML (path or dict)."""
    t0 = time.time()
    source = str(config) if not isinstance(config, dict) else "<dict>"
    cfg = load_yaml(config) if not isinstance(config, dict) else config
    comp = compose(cfg, overrides=overrides, signal_points=points)
    general = {**cfg.get("General", {}), **(overrides or {})}
    out = pathlib.Path(general.get("OutputDir", "results")) / general["Name"]
    out.mkdir(parents=True, exist_ok=True)
    pruning = cfg.get("Pruning") or {}

    dump_yaml(comp.config, out / "cabinetry_config.yaml", header=CONFIG_HEADER.format(source=source))
    dump_yaml(cfg, out / "workspace_config.yaml", header=f"workspace YAML used ({source})")
    write_json(comp.meta, out / "meta.json")

    engine = TemplateEngine(comp, n_workers=n_workers)
    outputs = {"meta": out / "meta.json", "cabinetry_config": out / "cabinetry_config.yaml"}

    if comp.meta["fit_type"] != "excl":
        ws = _build_ws(engine, comp, comp.config, pruning)
        cabinetry.workspace.save(ws, out / "ws.json")
        outputs["workspace"] = out / "ws.json"
        log.info(f"workspace written to {out / 'ws.json'} ({time.time() - t0:.1f} s)")
        return outputs

    # exclusion: background-only workspace + one patch per signal point
    bkg_cfg = comp.config_for(None)
    ws = _build_ws(engine, comp, bkg_cfg, pruning)
    cabinetry.workspace.save(ws, out / "ws.json")
    outputs["workspace"] = out / "ws.json"
    engine.release([s["Name"] for s in bkg_cfg["Samples"]])  # background histograms no longer needed

    patches = []
    skipped = []
    sig_folder = pathlib.Path(bkg_cfg["General"]["HistogramFolder"]) / "signal"
    for i, point in enumerate(comp.signal_points):
        folder = sig_folder / point.name
        try:
            patch = _signal_patch(engine, comp, ws, point, folder, pruning)
        except (RuntimeError, FileNotFoundError, KeyError) as exc:
            # e.g. a DSID of the grid file without trees in signal.<lumi>.root
            log.error(f"signal point {point.name} skipped: {exc}")
            skipped.append(f"{point.name} {exc}")
            engine.release([point.name])
            continue
        patches.append(patch)
        engine.release([point.name])
        if not keep_histograms:
            shutil.rmtree(folder, ignore_errors=True)
        if (i + 1) % 10 == 0 or i + 1 == len(comp.signal_points):
            log.info(f"built signal patches {i + 1}/{len(comp.signal_points)}")

    (out / "skipped_points.txt").write_text("".join(f"{line}\n" for line in skipped))
    if not patches:
        raise RuntimeError(f"no signal patch could be built, see {out / 'skipped_points.txt'}")
    if skipped:
        log.warning(f"{len(skipped)} signal points skipped, see {out / 'skipped_points.txt'}")
    patchset = {
        "metadata": {
            "name": comp.meta["name"],
            # pyhf requires a HEPData (inspire) reference; placeholder until published
            "references": {"hepdata": str(general.get("HEPDataRecord", "ins0000000"))},
            "description": f"signal patches for grid {comp.grid.name}",
            "digests": {"sha256": pyhf.utils.digest(ws)},
            "labels": list(comp.grid.mass_labels),
        },
        "patches": patches,
        "version": "1.0.0",
    }
    pyhf.PatchSet(patchset)  # validation
    write_json(patchset, out / "patchset.json", indent=None)
    outputs["patchset"] = out / "patchset.json"
    if write_full_workspaces:
        pset = pyhf.PatchSet(patchset)
        for patch in pset.patches:
            full = pset.apply(pyhf.Workspace(ws), patch.name)
            cabinetry.workspace.save(dict(full), out / "workspaces" / f"{patch.name}.json")
    log.info(
        f"background workspace {out / 'ws.json'} and {len(patches)} signal patches written "
        f"({time.time() - t0:.1f} s)"
    )
    return outputs
